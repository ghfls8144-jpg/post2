export default async function handler(req, res) {
  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method not allowed" });
  }

  const { messages } = req.body;
  if (!messages || !Array.isArray(messages)) {
    return res.status(400).json({ error: "Invalid messages" });
  }

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    return res.status(500).json({ error: "API key not configured" });
  }

  const systemPrompt = `당신은 「중소기업창업 지원사업 통합관리지침」(2025년 12월 23일 전부개정)에 관한 전문 AI 어시스턴트입니다.

아래는 지침 전체 내용입니다:

---
${DOC_CONTENT}
---

이 지침 내용을 바탕으로 사용자의 질문에 정확하고 친절하게 답변해 주세요.
- 지침 내용에 근거한 사실만 답변하세요.
- 조항 번호나 해당 섹션을 명시하여 답변하면 좋습니다.
- 지침에 없는 내용은 없다고 명확히 알려주세요.
- 한국어로 답변하세요.
- 핵심 정보는 간결하게 요약하되, 중요한 기준(금액, 기간, 비율 등)은 반드시 포함하세요.`;

  // Gemini API 형식으로 대화 이력 변환
  // Gemini: role은 "user" / "model" 만 허용
  const geminiContents = messages.map((m) => ({
    role: m.role === "assistant" ? "model" : "user",
    parts: [{ text: m.content }],
  }));

  try {
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key=${apiKey}`,
      {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          system_instruction: {
            parts: [{ text: systemPrompt }],
          },
          contents: geminiContents,
          generationConfig: {
            maxOutputTokens: 1024,
            temperature: 0.3,
          },
        }),
      }
    );

    const data = await response.json();

    if (!response.ok) {
      const errMsg = data.error?.message || "Gemini API error";
      return res.status(response.status).json({ error: errMsg });
    }

    const reply =
      data.candidates?.[0]?.content?.parts?.map((p) => p.text || "").join("") ||
      "응답을 받지 못했습니다.";

    return res.status(200).json({ reply });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: "Internal server error" });
  }
}
